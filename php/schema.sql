CREATE TABLE grogu_users (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  name VARCHAR(100) NOT NULL,
  email VARCHAR(254) NOT NULL UNIQUE,
  password VARCHAR(255) NOT NULL,
  role VARCHAR(10) NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE grogu_sessions (
  token CHAR(64) CHARACTER SET ascii COLLATE ascii_bin PRIMARY KEY,
  user_id INT UNSIGNED NOT NULL,
  expires BIGINT NOT NULL,
  FOREIGN KEY (user_id) REFERENCES grogu_users(id) ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE grogu_projects (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  name VARCHAR(500) NOT NULL,
  domain VARCHAR(500) NOT NULL,
  stage_url VARCHAR(500) NOT NULL,
  host VARCHAR(500) NOT NULL,
  launch_date VARCHAR(10) NOT NULL,
  notes TEXT NOT NULL,
  designer_id INT UNSIGNED NULL,
  developer_id INT UNSIGNED NULL,
  tester_id INT UNSIGNED NULL,
  account_id INT UNSIGNED NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (designer_id) REFERENCES grogu_users(id) ON DELETE SET NULL,
  FOREIGN KEY (developer_id) REFERENCES grogu_users(id) ON DELETE SET NULL,
  FOREIGN KEY (tester_id) REFERENCES grogu_users(id) ON DELETE SET NULL,
  FOREIGN KEY (account_id) REFERENCES grogu_users(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE grogu_items (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  project_id INT UNSIGNED NOT NULL,
  section VARCHAR(255) NOT NULL,
  title TEXT NOT NULL,
  position INT NOT NULL,
  notes TEXT NOT NULL,
  designer TINYINT NOT NULL DEFAULT 0,
  developer TINYINT NOT NULL DEFAULT 0,
  content_admin TINYINT NOT NULL DEFAULT 0,
  tester TINYINT NOT NULL DEFAULT 0,
  account_exec TINYINT NOT NULL DEFAULT 0,
  not_applicable TINYINT NOT NULL DEFAULT 0,
  FOREIGN KEY (project_id) REFERENCES grogu_projects(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE grogu_login_attempts (
  address_hash CHAR(64) CHARACTER SET ascii COLLATE ascii_bin PRIMARY KEY,
  attempts INT NOT NULL,
  expires BIGINT NOT NULL
) ENGINE=InnoDB;
